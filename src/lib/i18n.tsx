export type UiLang = "en" | "fa";

export function translate(lang: UiLang | undefined, key: string): string {
  const table = lang === "fa" ? FA : EN;
  return table[key] ?? EN[key] ?? key;
}

type UiValue = { lang: UiLang; t: (key: string) => string };

const UiContext = createContext<UiValue>({ lang: "en", t: (key) => translate("en", key) });

export function UiProvider({ lang, children }: { lang: UiLang; children: ReactNode }) {
  useEffect(() => {
    document.documentElement.lang = lang === "fa" ? "fa" : "en";
    document.documentElement.dir = lang === "fa" ? "rtl" : "ltr";
  }, [lang]);
  const value = useMemo<UiValue>(() => ({ lang, t: (key) => translate(lang, key) }), [lang]);
  return <UiContext.Provider value={value}>{children}</UiContext.Provider>;
}

export function useUi(): UiValue {
  return useContext(UiContext);
}

export type UiLang = "en" | "fa";

export function formatTemplate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, k) => (params[k] != null ? String(params[k]) : `{{${k}}}`));
}

export function translate(
  lang: UiLang | undefined,
  key: string,
  params?: Record<string, string | number>
): string {
  const table = lang === "fa" ? FA : EN;
  const raw = table[key] ?? EN[key] ?? key;
  return formatTemplate(raw, params);
}

type UiValue = { lang: UiLang; t: (key: string, params?: Record<string, string | number>) => string };

const UiContext = createContext<UiValue>({ lang: "en", t: (key, params) => translate("en", key, params) });

export function UiProvider({ lang, children }: { lang: UiLang; children: ReactNode }) {
  useEffect(() => {
    document.documentElement.lang = lang === "fa" ? "fa" : "en";
    document.documentElement.dir = lang === "fa" ? "rtl" : "ltr";
  }, [lang]);
  const value = useMemo<UiValue>(() => ({ lang, t: (key, params) => translate(lang, key, params) }), [lang]);
  return <UiContext.Provider value={value}>{children}</UiContext.Provider>;
}

export function useUi(): UiValue {
  return useContext(UiContext);
}
